package tech.yobit.web3.contract;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.web3j.abi.TypeEncoder;
import org.web3j.crypto.ContractUtils;
import org.web3j.crypto.Credentials;
import org.web3j.crypto.Hash;
import org.web3j.protocol.Web3j;
import org.web3j.protocol.core.methods.response.TransactionReceipt;
import org.web3j.protocol.http.HttpService;
import org.web3j.utils.Numeric;
import tech.yobit.generated.gateway.Gateway;
import tech.yobit.generated.wallet.Wallet;
import tech.yobit.web3.types.Address;
import tech.yobit.web3.types.Blockchain;
import tech.yobit.web3.types.ERC20Meta;
import tech.yobit.web3.types.ContractAddress;

/**
 * 1. one gateway multiple wallet
 * 2. one user multiple wallet
 * 3. different wallet different user, or different blockchain
 * 4. all gateway is control by one private key
 */
public class GatewayContract {
    private static final Logger log = LoggerFactory.getLogger(GatewayContract.class);

    private final Blockchain mBlockchain;
    private final Address mOwnerAddress;
    private final Gateway mGateway;

    // don't need to record WalletContract own to it maybe unlimited

    public GatewayContract(Credentials credentials, Blockchain blockchain) {
        mBlockchain = blockchain;
        mOwnerAddress = Address.fromHex(credentials.getAddress());

        Web3j web3j = Web3j.build(new HttpService(blockchain.url));
        mGateway = Gateway.load(
                blockchain.gatewayAddress.toHex(),
                web3j, credentials, new GasProvider(blockchain.id, blockchain.url)
        );

        log.info("Gateway {} connected to {}({}) network",
                blockchain.gatewayAddress.toHex(), blockchain.name, blockchain.id);
    }

    private byte[] generateSalt(String salt) {
        byte[] bytes = salt.getBytes();
        return Hash.sha256(bytes);
    }

    private String generateInitCode() {
        return Wallet.BINARY + TypeEncoder.encode(mOwnerAddress);
    }

    private ContractAddress predictWalletAddress(byte[] salt) {
        String initCode = generateInitCode();

        byte[] address = ContractUtils.generateCreate2ContractAddress(
                mBlockchain.gatewayAddress.toBytes(), salt, Numeric.hexStringToByteArray(initCode)
        );
        return new ContractAddress(mBlockchain.id, address);
    }

    public ContractAddress predictWalletAddress(String uid) {
        byte[] salt = generateSalt(uid);
        return predictWalletAddress(salt);
    }

    public boolean checkWalletAddress(Address address) throws Exception {
        return mGateway.wallets(address.toHex()).send();
    }

    private ContractAddress createWallet(byte[] salt) throws Exception {
        TransactionReceipt tx = mGateway.createWallet(salt).send();
        log.info("create wallet for {} in {}({}) network, txId {}, status {}, gas used {}",
                Numeric.toHexString(salt), mBlockchain.name, mBlockchain.id,
                tx.getTransactionHash(), tx.isStatusOK(), tx.getGasUsed()
        );

        if (!tx.isStatusOK()) {
            log.warn("create wallet for {} failure, revert reason: {}",
                    Numeric.toHexString(salt), tx.getRevertReason());
            return null;
        }

        // the first log is the contract creating log generated by blockchain contract creating event
        String address = tx.getLogs().getFirst().getAddress();
        log.info("deploy wallet contract {} for {} in {}({}) network",
                address, Numeric.toHexString(salt),
                mBlockchain.name, mBlockchain.id
        );
        return new ContractAddress(mBlockchain.id, address);
    }

    public ContractAddress createWallet(String uid) throws Exception {
        byte[] salt = generateSalt(uid);

        return createWallet(salt);
    }

    /*
     *  1. return wallet address if wallet already exists
     *  2. create then return wallet address if wallet don't exist
     */
    public ContractAddress checkAndCreateWallet(String uid, Address address) throws Exception {
        byte[] salt = generateSalt(uid);
        ContractAddress predicted = predictWalletAddress(salt);

        // 1st check
        if (!address.equals(predicted)) {
            throw new Exception(String.format(
                    "uid %s generate wallet address %s not match predict address %s",
                    uid, address, predicted)
            );
        }

        boolean exist = checkWalletAddress(predicted);
        if (exist) {
            return predicted;
        }

        ContractAddress generate = createWallet(salt);
        // 2nd check
        if (generate != null && generate.equals(predicted)) {
            return predicted;
        } else if (generate != null) {
            log.error("predict address {} don't match generated {}",
                    predicted.toHex(), generate.toHex()
            );
        }

        return null;
    }

    public WalletContract getWalletContract(Address address, ERC20Meta[] coinMetas, String uid, Credentials credentials) {
        return new WalletContract(address, mBlockchain, coinMetas, credentials, uid, this);
    }
}
